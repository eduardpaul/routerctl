"""Generate asusrouter/register/register.go.

It blank-imports every Go package that registers sources or actions (the
Go `load_all_sources`).

    uv run --project parity python parity/gen_go_register.py
"""

from __future__ import annotations

from pathlib import Path
import re
import subprocess

ROOT = Path(__file__).resolve().parent.parent
# The Go port of this library (see asusrouter/PARITY.md)
GO = ROOT / "asusrouter"
CALL = re.compile(r"\bregistry\.Register(Source|Action)\(")


def go_module_path(directory: Path) -> str:
    """Return the import path of `directory`, from the nearest go.mod."""

    for parent in (directory, *directory.parents):
        gomod = parent / "go.mod"
        if not gomod.is_file():
            continue
        for line in gomod.read_text(encoding="utf-8").splitlines():
            match = re.match(r"\s*module\s+(\S+)", line)
            if match:
                module = match.group(1).strip('"')
                rel = directory.relative_to(parent).as_posix()
                return module if rel == "." else f"{module}/{rel}"
        break
    msg = f"no go.mod with a module line at or above {directory}"
    raise SystemExit(msg)


MODULE = go_module_path(GO)


def main() -> int:
    """Write register.go from the packages that register something."""

    pkgs: set[str] = set()
    for path in (GO / "modules").rglob("*.go"):
        if path.name.endswith("_test.go"):
            continue
        if CALL.search(path.read_text(encoding="utf-8")):
            pkgs.add(str(path.parent.relative_to(GO)))
    lines = "".join(f'\t_ "{MODULE}/{p}"\n' for p in sorted(pkgs))
    out = GO / "register" / "register.go"
    out.parent.mkdir(exist_ok=True)
    out.write_text(
        "// Code generated by parity/gen_go_register.py. DO NOT EDIT.\n\n"
        "// Package register imports every module that registers sources or\n"
        "// actions (Python `load_all_sources`). Blank-import it once:\n"
        "//\n"
        f'//\timport _ "{MODULE}/register"\n'
        "package register\n\n"
        f"import (\n{lines})\n",
        encoding="utf-8",
    )
    subprocess.run(["gofmt", "-w", str(out)], check=True)
    print(f"{len(pkgs)} packages -> {out.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

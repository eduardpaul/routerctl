"""Generate the Go enum files from the Python enums.

Every `Enum` defined under `asusrouter.modules` becomes a Go type in the
mirrored Go package (see asusrouter/PARITY.md), written to
`<pkg>/<pyfile>_enums_gen.go` (`enums.py` -> `enums_gen.go`). Re-run
after changing a Python enum:

    uv run --project parity python parity/gen_go_enums.py

Python is the source of truth for enum members and values; never edit the
generated Go files by hand.
"""

from __future__ import annotations

import enum
import importlib
import json
from pathlib import Path
import pkgutil
import re
import subprocess
import sys

import asusrouter
from asusrouter.modules.source import ARDataType
from asusrouter.tools.enum import FromIntMixin, FromStrMixin

ROOT = Path(__file__).resolve().parent.parent
# The Go port of this library (see asusrouter/PARITY.md)
GO_ROOT = ROOT / "asusrouter"

# The Python library must come from the pinned submodule: without it,
# `import asusrouter` can resolve to the Go asusrouter/ directory as an
# empty namespace package
_PYLIB = (ROOT / "third_party" / "asusrouter-py").resolve()
_FILE = asusrouter.__file__
if not _FILE or not Path(_FILE).resolve().is_relative_to(_PYLIB):
    sys.exit(
        "asusrouter is not the submodule library: run "
        "git submodule update --init && uv sync --project parity"
    )


def go_module_path(directory: Path) -> str:
    """Return the import path of `directory`, from the nearest go.mod."""

    for parent in (directory, *directory.parents):
        gomod = parent / "go.mod"
        if not gomod.is_file():
            continue
        for line in gomod.read_text(encoding="utf-8").splitlines():
            match = re.match(r"\s*module\s+(\S+)", line)
            if match:
                module = match.group(1).strip('"')
                rel = directory.relative_to(parent).as_posix()
                return module if rel == "." else f"{module}/{rel}"
        break
    msg = f"no go.mod with a module line at or above {directory}"
    raise SystemExit(msg)


GO_MODULE = go_module_path(GO_ROOT)

# Packages in the device identity's import closure: their registry/identity
# wiring files live in a subpackage named after the file
# (asusrouter/PARITY.md)
SPLIT_PACKAGES = {
    "aimesh",
    "common",
    "device",
    "firmware",
    "nvram",
    "ports",
    "support",
    "wifi",
}
WIRING_FILES = {"source", "action", "probe", "recovery"}

HEADER = (
    "// Code generated by parity/gen_go_enums.py from {src}. DO NOT EDIT.\n"
)


def go_package_name(directory: Path) -> str:
    """Go package name for a directory: its name without underscores."""

    return directory.name.replace("_", "")


def camel(name: str) -> str:
    """`BAND_2G1` -> `Band2g1`."""

    return "".join(
        part[:1].upper() + part[1:].lower() for part in name.split("_") if part
    )


def go_dir_for(module: object) -> tuple[Path, str] | None:
    """Return (go directory, file stem) for a Python module, or None."""

    name = module.__name__  # type: ignore[attr-defined]
    parts = name.split(".")
    if len(parts) < 3 or parts[1] != "modules":
        return None
    is_pkg = Path(module.__file__).name == "__init__.py"  # type: ignore[attr-defined]
    rel = parts[2:]
    if is_pkg:
        dirs, stem = rel, rel[-1]
    else:
        dirs, stem = rel[:-1], rel[-1]
        if dirs and dirs[0] in SPLIT_PACKAGES and stem in WIRING_FILES:
            dirs = [*dirs, stem]
    return GO_ROOT.joinpath("modules", *dirs), stem


def go_literal(value: object) -> str:
    """Render an enum value as a Go literal (int or quoted string)."""

    if isinstance(value, bool):
        raise TypeError("bool enum values are not supported")
    if isinstance(value, int):
        return str(value)
    return json.dumps(str(value), ensure_ascii=False)


def go_identifiers(cls: type[enum.Enum]) -> dict[str, str]:
    """Map every member name (aliases included) to a unique Go name."""

    used: set[str] = set()
    ident: dict[str, str] = {}
    for member_name in cls.__members__:
        go_name = cls.__name__ + camel(member_name)
        while go_name in used:
            go_name += "_"
        used.add(go_name)
        ident[member_name] = go_name
    return ident


def render_type(
    cls: type[enum.Enum], ident: dict[str, str], gotype: str
) -> list[str]:
    """Render the doc comment, the Go type and its constants."""

    name = cls.__name__
    mixins = [
        b.__name__ for b in cls.__mro__ if b in (FromIntMixin, FromStrMixin)
    ]
    kind = "IntEnum" if gotype == "int" else "StrEnum"
    out = [
        (
            f"// {name} mirrors `{cls.__module__}.{name}` "
            f"({', '.join([*mixins, kind])})."
        )
    ]
    doc = (cls.__doc__ or "").strip().splitlines()
    if doc:
        out.append(f"// {doc[0]}")
    out.append(f"type {name} {gotype}\n")
    out.append("const (")
    for member_name, member in cls.__members__.items():
        alias = (
            ""
            if member.name == member_name
            else f" // alias of {ident[member.name]}"
        )
        value = go_literal(member.value)
        out.append(f"\t{ident[member_name]} {name} = {value}{alias}")
    out.append(")\n")
    return out


def render_tables(
    cls: type[enum.Enum], ident: dict[str, str], priv: str
) -> list[str]:
    """Render the member list, the name lookups, Name and Valid."""

    name = cls.__name__
    members = list(cls)
    out = [
        (
            f"// {name}Members lists the members in definition order "
            "(aliases excluded)."
        ),
        f"var {name}Members = []{name}{{",
    ]
    out.extend(f"\t{ident[member.name]}," for member in members)
    out.append("}\n")

    out.append(f"var {priv}ByName = map[string]{name}{{")
    out.extend(
        f"\t{json.dumps(member_name)}: {ident[member_name]},"
        for member_name in cls.__members__
    )
    out.append("}\n")

    out.append(f"var {priv}Names = map[{name}]string{{")
    out.extend(
        f"\t{ident[member.name]}: {json.dumps(member.name)},"
        for member in members
    )
    out.append("}\n")

    out.append("// Name returns the Python member name.")
    out.append(f"func (e {name}) Name() string {{ return {priv}Names[e] }}\n")
    out.append("// Valid reports whether e is a defined member.")
    out.append(
        f"func (e {name}) Valid() bool "
        f"{{ _, ok := {priv}Names[e]; return ok }}\n"
    )
    return out


def render_from_value_ok(name: str, priv: str, *, is_int: bool) -> list[str]:
    """Render <Name>FromValueOK, `from_value` without the fallback."""

    out = [
        (
            f"// {name}FromValueOK mirrors `{name}.from_value` "
            "without the UNKNOWN fallback."
        ),
        f"func {name}FromValueOK(value any) ({name}, bool) {{",
        "\tswitch v := value.(type) {",
        f"\tcase {name}:",
        "\t\treturn v, v.Valid()",
        f"\tcase *{name}:",
        "\t\tif v != nil {",
        "\t\t\treturn *v, v.Valid()",
        "\t\t}",
        "\t}",
    ]
    if is_int:
        out += [
            "\tif vint := converters.RawToInt(value); vint != nil {",
            f"\t\tif m := {name}(*vint); m.Valid() {{",
            "\t\t\treturn m, true",
            "\t\t}",
            "\t}",
        ]
    out.append("\tif vstr := converters.RawToStr(value); vstr != nil {")
    if not is_int:
        out += [
            f"\t\tif m := {name}(*vstr); m.Valid() {{",
            "\t\t\treturn m, true",
            "\t\t}",
        ]
    out += [
        f"\t\tif m, ok := {priv}ByName[strings.ToUpper(*vstr)]; ok {{",
        "\t\t\treturn m, true",
        "\t\t}",
        "\t}",
        f"\tvar zero {name}",
        "\treturn zero, false",
        "}\n",
    ]
    return out


def render_from_value(name: str, unknown: str | None) -> list[str]:
    """Render <Name>FromValue, `from_value` with its UNKNOWN fallback."""

    out = [
        f"// {name}FromValue mirrors `{name}.from_value`"
        + (
            f": unresolved values map to {unknown}."
            if unknown
            else " (no UNKNOWN member: unresolved values give the zero value)."
        ),
        f"func {name}FromValue(value any) {name} {{",
        f"\tif m, ok := {name}FromValueOK(value); ok {{",
        "\t\treturn m",
        "\t}",
    ]
    if unknown:
        out.append(f"\treturn {unknown}")
    else:
        out += [f"\tvar zero {name}", "\treturn zero"]
    out.append("}\n")
    return out


def render_source(name: str, gotype: str) -> list[str]:
    """Render SourceName and SourceKey for ARDataType enums."""

    return [
        f"// SourceName makes {name} members usable as data requests.",
        (
            f"func (e {name}) SourceName() string "
            f"{{ return {json.dumps(name)} }}\n"
        ),
        "// SourceKey returns the member value as the request key.",
        (
            f"func (e {name}) SourceKey() []any "
            f"{{ return []any{{{gotype}(e)}} }}\n"
        ),
    ]


def render_enum(cls: type[enum.Enum]) -> str:
    """Render one enum as Go source."""

    name = cls.__name__
    members = list(cls)
    if not members:
        return ""
    is_int = all(isinstance(m.value, int) for m in members)
    gotype = "int" if is_int else "string"
    priv = name[:1].lower() + name[1:]
    ident = go_identifiers(cls)
    unknown = ident["UNKNOWN"] if "UNKNOWN" in cls.__members__ else None

    out = render_type(cls, ident, gotype)
    out += render_tables(cls, ident, priv)
    out += render_from_value_ok(name, priv, is_int=is_int)
    out += render_from_value(name, unknown)
    if issubclass(cls, ARDataType):
        out += render_source(name, gotype)
    return "\n".join(out)


def collect() -> dict[tuple[Path, str], list[type[enum.Enum]]]:
    """Group the enums of `asusrouter.modules` by target Go file."""

    files: dict[tuple[Path, str], list[type[enum.Enum]]] = {}
    seen: set[type] = set()
    for info in pkgutil.walk_packages(asusrouter.__path__, "asusrouter."):
        module = importlib.import_module(info.name)
        target = go_dir_for(module)
        if target is None:
            continue
        for obj in vars(module).values():
            if (
                isinstance(obj, type)
                and issubclass(obj, enum.Enum)
                and obj.__module__ == module.__name__
                and obj not in seen
                and list(obj)
            ):
                seen.add(obj)
                files.setdefault(target, []).append(obj)
    return files


def main() -> int:
    """Write every enum file, gofmt them and list them."""

    files = collect()
    written = []
    for (directory, stem), classes in sorted(
        files.items(), key=lambda kv: str(kv[0])
    ):
        directory.mkdir(parents=True, exist_ok=True)
        src = classes[0].__module__
        body = "\n".join(render_enum(cls) for cls in classes)
        imports = ['"strings"', f'"{GO_MODULE}/tools/converters"']
        text = (
            HEADER.format(src=src)
            + f"\npackage {go_package_name(directory)}\n\n"
            + "import (\n"
            + "".join(f"\t{i}\n" for i in imports)
            + ")\n\n"
            + body
            + "\n"
        )
        target = directory / (
            "enums_gen.go" if stem == "enums" else f"{stem}_enums_gen.go"
        )
        target.write_text(text, encoding="utf-8")
        written.append(target)
    subprocess.run(["gofmt", "-w", *map(str, written)], check=True)
    for path in written:
        print(path.relative_to(ROOT))
    print(
        f"{sum(len(c) for c in files.values())} enums in {len(written)} files",
        file=sys.stderr,
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

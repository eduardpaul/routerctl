"""Check that the Go port mirrors the Python package.

Every Go directory under asusrouter must map to a Python package or
file of `asusrouter/`, and every Go file in it to a Python file, unless it
is on the Go-only allowlist below (see asusrouter/PARITY.md, "Layout").
Run from anywhere:

    uv run --project parity python parity/check_layout.py
"""

from __future__ import annotations

from fnmatch import fnmatch
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parent.parent
PY = ROOT / "third_party" / "asusrouter-py" / "asusrouter"
GO = ROOT / "asusrouter"

# Go names that differ from the Python ones (Go keyword / stdlib clash)
RENAMES = {"consts": "const.py", "arerror": "error.py"}

# Go directories whose files map into another Python package: the support
# source part of `support/__init__.py` plus its translators (one Go file
# per Python file; `source.go` is the `__init__.py` part)
SPLIT_INTO = {"modules/support/source": ("modules/support", "source")}

# Go-only directories (glob on the path relative to asusrouter)
GO_ONLY_DIRS = {
    "parity/*": "Go side of the parity harness (canonical form, replay)",
    "cmd/*": "Go-only commands (cmd/parity for parity/check.sh)",
    "register": "generated by parity/gen_go_register.py",
    "*/internal/*": "Go-only implementation details",
    "modules/device/devicetest": "test helpers (recorded identities)",
}

# Go-only files (path relative to asusrouter) and why they exist
GO_ONLY_FILES = {
    "tls_pin.go": "thin wrapper over netkit/tlspin",
    "transport_replay.go": "replay transport over parity/replay",
    "identity_sync.go": "the identity wiring part of asusrouter.py",
    "tools/converters/pystr.go": "Python str/int/float builtins",
    "tools/converters/datetime.go": "fromisoformat / strptime",
    "tools/readers/literal.go": "ast.literal_eval subset",
    "tools/readers/pyjson.go": "json.loads",
}


def go_only_dir(rel: str) -> bool:
    """Return whether a Go directory is on the Go-only allowlist."""

    return any(
        fnmatch(rel, pattern) or fnmatch(rel + "/", pattern)
        for pattern in GO_ONLY_DIRS
    )


def stem_of(name: str) -> str:
    """Return the Python stem of a Go file name.

    `x.go` and `x_enums_gen.go` give `x`; `enums_gen.go` gives `enums`.
    """

    stem = name.removesuffix(".go")
    if stem == "enums_gen":
        return "enums"
    return stem.removesuffix("_enums_gen")


def go_files(go_dir: Path) -> list[Path]:
    """Return the non-test Go files of a directory."""

    return [
        p
        for p in sorted(go_dir.glob("*.go"))
        if not p.name.endswith("_test.go")
    ]


def check_files(
    go_dir: Path, py_dir: Path, init_stem: str, errors: list[str]
) -> None:
    """Check that every Go file of go_dir maps to a .py file of py_dir.

    `<init_stem>.go` maps to `__init__.py`.
    """

    init_stems = {init_stem, init_stem.replace("_", "")}
    has_init = (py_dir / "__init__.py").is_file()
    for go_file in go_files(go_dir):
        frel = go_file.relative_to(GO).as_posix()
        stem = stem_of(go_file.name)
        if frel in GO_ONLY_FILES or (py_dir / f"{stem}.py").is_file():
            continue
        if stem in init_stems and has_init:
            continue
        py_rel = py_dir.relative_to(ROOT).as_posix()
        errors.append(
            f"asusrouter/{frel}: no {py_rel}/{stem}.py"
            f" (nor __init__.py for {init_stem}.go)"
        )


def check_dir(go_dir: Path, errors: list[str]) -> None:
    """Check one Go directory against the Python tree."""

    rel = go_dir.relative_to(GO).as_posix()
    if rel != "." and go_only_dir(rel):
        return
    if rel in SPLIT_INTO:
        target, init_stem = SPLIT_INTO[rel]
        check_files(go_dir, PY / target, init_stem, errors)
        return
    if rel in RENAMES:
        if not (PY / RENAMES[rel]).is_file():
            errors.append(
                f"asusrouter/{rel}/: renamed from"
                f" asusrouter/{RENAMES[rel]}, which is missing"
            )
        return
    py_dir = PY if rel == "." else PY / rel
    if py_dir.is_dir():
        init_stem = "asusrouter" if rel == "." else go_dir.name
        check_files(go_dir, py_dir, init_stem, errors)
        return
    if (PY / f"{rel}.py").is_file():
        # A subpackage named after a Python file (import-cycle split):
        # one Go file, named after it.
        errors.extend(
            f"asusrouter/{go_file.relative_to(GO).as_posix()}: split"
            f" package of asusrouter/{rel}.py must hold only"
            f" {go_dir.name}.go"
            for go_file in go_files(go_dir)
            if stem_of(go_file.name) != go_dir.name
        )
        return
    errors.append(
        f"asusrouter/{rel}/: no asusrouter/{rel}/ nor"
        f" asusrouter/{rel}.py (and not Go-only)"
    )


def main() -> int:
    """Check the layout; print the problems and return 1 on any."""

    errors: list[str] = []
    dirs = sorted({p.parent for p in GO.rglob("*.go")})
    for go_dir in dirs:
        check_dir(go_dir, errors)
    errors.extend(
        f"stale allowlist entry: asusrouter/{frel} does not exist"
        for frel in sorted(GO_ONLY_FILES)
        if not (GO / frel).is_file()
    )
    for msg in errors:
        sys.stderr.write(f"layout: {msg}\n")
    if errors:
        sys.stderr.write(
            f"layout: {len(errors)} problem(s); see"
            ' asusrouter/PARITY.md "Layout"\n'
        )
        return 1
    sys.stdout.write(f"layout OK: {len(dirs)} Go directories\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
